/* Main menu and board HUD art: art/ui/*.png (designer's final art; panel-gold / panel-silver = the board's player panels, panel-silver made from the gold one) → src/partui.js, each scaled to about twice its size on the 1280 x 720 menu and embedded as WebP (UI_ART, set as CSS variables --ui-<name> by part3).
   Roster rocks: dark rock-d1 / d2 / d4 / d5, and a white version of each shape (rock-w1 / w2 / w4 / w5, the selected truck's slab).
   node tools/uiart.mjs */
import { chromium } from "playwright";
import fs from "fs";
const W = {
	"bb-yellow": 720,
	"bb-green": 360,
	"bb-white": 360,
	"bb-dark1": 300,
	"bb-dark2": 300,
	plate3: 600,
	"arrow3-l": 128,
	"arrow3-r": 128,
	"rock-d1": 160,
	"rock-d2": 160,
	"rock-d4": 170,
	"rock-d5": 165,
	"rock-w1": 180,
	"rock-w2": 180,
	"rock-w4": 185,
	"rock-w5": 185,
	"panel-gold": 600,
	"panel-silver": 600,
};
for (let i = 1; i <= 6; i++) W["dtile-" + i] = 112;
const dir = new URL("../art/ui/", import.meta.url);
const br = await chromium.launch();
const pg = await br.newPage();
const out = {};
let total = 0;
for (const f of fs
	.readdirSync(dir)
	.filter((f) => f.endsWith(".png"))
	.sort()) {
	const k = f.slice(0, -4),
		b64 = fs.readFileSync(new URL(f, dir)).toString("base64");
	out[k] = await pg.evaluate(
		async ({ b64, w }) => {
			const im = new Image();
			im.src = "data:image/png;base64," + b64;
			await im.decode();
			const sw = Math.min(w, im.width),
				sh = Math.round((im.height * sw) / im.width);
			const c = document.createElement("canvas");
			c.width = sw;
			c.height = sh;
			const x = c.getContext("2d");
			x.imageSmoothingQuality = "high";
			x.drawImage(im, 0, 0, sw, sh);
			return c.toDataURL("image/webp", 0.88);
		},
		{ b64, w: W[k] || 200 },
	);
	total += out[k].length;
}
await br.close();
fs.writeFileSync(
	new URL("../src/partui.js", import.meta.url),
	`/* ---------- main menu art (generated by tools/uiart.mjs from art/ui/, don't hand-edit) ---------- */\nconst UI_ART = ${JSON.stringify(out)};\n`,
);
console.log(Object.keys(out).length, "images,", Math.round(total / 1024), "KB of data URIs");
